import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { REGISTRY, registryJsonWithThirdApp, THIRD_APP } from "./helpers.ts";

const WIZARD = join(import.meta.dirname, "..", "scripts", "wizard");
const SCRIPT = join(WIZARD, "redacted-reader.sh");
const FETCH = join(WIZARD, "fetch-redacted-sql.sh");
const KNOWN_PASSWORD = "Aa1-knownReaderPassword0123456789";
const shop = REGISTRY.apps.get("shop")!;
const crm = REGISTRY.apps.get("crm")!;

// The shape hyde-db generates for one model view (prisma/redacted/redacted-views.sql).
function applyScript(view: string): string {
  return [
    "-- GENERATED by hyde-db from schema.prisma. Do not edit by hand.",
    "SET @hyde_sql = IF(@hyde_refused IS NULL, CONCAT('CREATE DEFINER = CURRENT_USER SQL SECURITY DEFINER VIEW `redacted`.`hyde_db_marker` AS SELECT ''Generated by hyde-db'' AS `marker`, ', 'x', ' AS `source`;'), 'DO 0');",
    `SET @hyde_sql = IF(@hyde_refused IS NULL, 'CREATE DEFINER = CURRENT_USER SQL SECURITY DEFINER VIEW \`redacted\`.\`${view}\` (\`id\`, \`status\`) AS SELECT \`id\`, \`status\` FROM \`${view}Table\`;', 'DO 0');`,
    "",
  ].join("\n");
}

/** `dir/<app>/` with the three files the wizard reads. */
function appFiles(dir: string, app: string, view: string): string {
  mkdirSync(join(dir, app));
  writeFileSync(join(dir, app, "redacted-views.sql"), applyScript(view));
  writeFileSync(join(dir, app, "redacted-views-drop.sql"), "-- GENERATED by hyde-db.\n");
  writeFileSync(join(dir, app, "ca.pem"), "-----BEGIN CERTIFICATE-----\nAA==\n-----END CERTIFICATE-----\n");
  return join(dir, app, "redacted-views.sql");
}

function wizard(args: string[], env: Record<string, string> = {}) {
  const run = spawnSync("bash", [SCRIPT, ...args], { env: { ...process.env, ROTATE: "0", ...env }, input: "", encoding: "utf8" });
  return { status: run.status, out: `${run.stdout}${run.stderr}`, stderr: run.stderr };
}

describe("redacted-reader.sh --dry-run", () => {
  let dir: string;
  let env: string;
  let run: ReturnType<typeof wizard>;
  let out: string;

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), "redacted-reader-"));
    const paths = [appFiles(dir, "shop", "ShopView"), appFiles(dir, "crm", "CrmView")];
    // crm has run before: its password is reused. shop gets a generated one.
    env = join(dir, "apply.env");
    writeFileSync(env, `HYDE_APP_CRM_REDACTED_URL='mysql://redacted_reader:${KNOWN_PASSWORD}@h.example:1/redacted?ssl=true'\n`);
    // One path per app, in apps.json order.
    run = wizard(["--dry-run", ...paths], { APPLY_ENV: env });
    out = run.out;
  });
  afterAll(() => rmSync(dir, { recursive: true, force: true }));

  it("exits 0", () => {
    expect(out).not.toMatch(/✗/);
    expect(run.status).toBe(0);
  });

  it("offers host, port and source database from apps.json", () => {
    for (const app of [shop, crm]) {
      expect(out).toContain(`Host: ${app.database.host}`);
      expect(out).toContain(`Port: ${app.database.port}`);
      expect(out).toContain(`-h ${app.database.host} -P ${app.database.port}`);
    }
  });

  it("names both apps' first view and refuses their source table", () => {
    expect(out).toContain("SELECT 1 FROM `redacted`.`CrmView` LIMIT 1;");
    expect(out).toContain("SELECT 1 FROM `redacted`.`ShopView` LIMIT 1;");
    expect(out).toContain(`SELECT 1 FROM \`${crm.database.sourceDatabase}\`.\`CrmViewTable\` LIMIT 1;`);
    expect(out).toContain(`SELECT 1 FROM \`${shop.database.sourceDatabase}\`.\`ShopViewTable\` LIMIT 1;`);
  });

  it("masks the reader password in every statement and connection string", () => {
    expect(out).not.toContain(KNOWN_PASSWORD);
    // A generated password (shop) starts with Aa1- and must not show either.
    expect(out).not.toMatch(/Aa1-[A-Za-z0-9-]{20,}/);
    expect(out.match(/IDENTIFIED BY '\*\*\*\*' REQUIRE SSL ACCOUNT UNLOCK;/g)).toHaveLength(2);
    expect(out).toContain("HYDE_APP_CRM_REDACTED_URL='mysql://redacted_reader:****@");
    expect(out).toContain("HYDE_APP_SHOP_REDACTED_URL='mysql://redacted_reader:****@");
    expect(out).toMatch(/\/redacted\?ssl=true'/);
  });

  it("writes nothing", () => {
    expect(readFileSync(env, "utf8")).toBe(
      `HYDE_APP_CRM_REDACTED_URL='mysql://redacted_reader:${KNOWN_PASSWORD}@h.example:1/redacted?ssl=true'\n`,
    );
  });
});

describe("redacted-reader.sh --dry-run --app shop (D37)", () => {
  let dir: string;
  let run: ReturnType<typeof wizard>;
  let out: string;

  beforeAll(() => {
    // Only shop's files exist: crm's are neither given nor needed.
    dir = mkdtempSync(join(tmpdir(), "redacted-reader-shop-"));
    run = wizard(["--dry-run", "--app", "shop", appFiles(dir, "shop", "ShopView")], { APPLY_ENV: join(dir, "apply.env") });
    out = run.out;
  });
  afterAll(() => rmSync(dir, { recursive: true, force: true }));

  it("exits 0 and runs shop's stages only", () => {
    expect(out).not.toMatch(/✗/);
    expect(run.status).toBe(0);
    expect(out).toContain("Stage 6/6 · shop: write HYDE_APP_SHOP_REDACTED_URL");
    expect(out).not.toMatch(/Stage \d+\/11/);
  });

  it("touches shop and never crm", () => {
    expect(out).toContain("SELECT 1 FROM `redacted`.`ShopView` LIMIT 1;");
    expect(out).toContain("HYDE_APP_SHOP_REDACTED_URL='mysql://redacted_reader:****@");
    expect(out).not.toMatch(/crm|CRM/);
    expect(out.match(/IDENTIFIED BY '\*\*\*\*' REQUIRE SSL ACCOUNT UNLOCK;/g)).toHaveLength(1);
  });

  it("refuses an app not in apps.json, and a path count that does not match the apps", () => {
    const bad = wizard(["--dry-run", "--app", "other"]);
    expect(bad.status).toBe(2);
    expect(bad.stderr).toMatch(/apps: shop crm/);
    const lone = wizard(["--dry-run", join(dir, "shop", "redacted-views.sql")]);
    expect(lone.status).toBe(2);
    expect(lone.stderr).toMatch(/usage:/);
  });
});

describe("a third app in apps.json (D38)", () => {
  let dir: string;
  let registry: string;

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), "redacted-reader-third-"));
    registry = join(dir, "apps.json");
    writeFileSync(registry, JSON.stringify(registryJsonWithThirdApp()));
  });
  afterAll(() => rmSync(dir, { recursive: true, force: true }));

  it("the reader wizard configures it from its entry, with no code change", () => {
    const sql = appFiles(dir, "help-desk", "HelpDeskView");
    const run = wizard(["--dry-run", "--app", "help-desk", sql], { APPLY_ENV: join(dir, "apply.env"), HYDE_APPS_FILE: registry });
    expect(run.out).not.toMatch(/✗/);
    expect(run.status).toBe(0);
    expect(run.out).toContain(`-h ${THIRD_APP.database.host} -P ${THIRD_APP.database.port}`);
    expect(run.out).toContain(`SELECT 1 FROM \`${THIRD_APP.database.sourceDatabase}\`.\`HelpDeskViewTable\` LIMIT 1;`);
    expect(run.out).toContain("Stage 6/6 · help-desk: write HYDE_APP_HELP_DESK_REDACTED_URL");
  });

  it("fetch-redacted-sql.sh --dry-run reads repo, SQL path and CA source from apps.json", () => {
    const run = spawnSync("bash", [FETCH, "--dry-run", "--app", "help-desk", "--out", join(dir, "out")], {
      env: { ...process.env, HYDE_APPS_FILE: registry },
      encoding: "utf8",
    });
    expect(run.status).toBe(0);
    const { repo, redactedSqlPath, database: { caSource } } = THIRD_APP;
    expect(run.stdout).toContain(`would fetch ${repo}@main:${redactedSqlPath}/redacted-views.sql`);
    expect(run.stdout).toContain(`would fetch ${repo}@main:${redactedSqlPath}/redacted-views-drop.sql`);
    expect(run.stdout).toContain(`would fetch ${caSource.repo}@${caSource.ref}:${caSource.path}`);
    expect(run.stdout).toContain("redacted-reader.sh --app help-desk");
    expect(run.stdout).not.toMatch(/shop|crm/);
  });

  it("fetch-redacted-sql.sh takes the CA ref from the entry and refuses an unregistered app", () => {
    const run = spawnSync("bash", [FETCH, "--dry-run", "--app", "crm"], { encoding: "utf8" });
    expect(run.status).toBe(0);
    expect(run.stdout).toContain(`would fetch ${crm.database.caSource.repo}@${crm.database.caSource.ref}:${crm.database.caSource.path}`);
    const bad = spawnSync("bash", [FETCH, "--dry-run", "--app", "help-desk"], { encoding: "utf8" });
    expect(bad.status).toBe(2);
    expect(bad.stderr).toMatch(/--app needs one of shop crm/);
  });
});
